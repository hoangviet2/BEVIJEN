"""Agent tool endpoints — AgentCore Gateway OpenAPI target only (design §9.6).

Auth: `x-api-key` injected by the Gateway from the AgentCore Identity API-key
provider. Bind `/tools/*` to its own listener / security-group rule so only
the Gateway can reach it. The OpenAPI document the Gateway imports is
`backend/gateway/openapi-tools.json` (generated by `python -m app.cli gateway-openapi`).
"""

from __future__ import annotations

from fastapi import APIRouter, Depends, HTTPException

from ..ai import parse_schedule as parse_schedule_text
from ..auth import ctx_dep, tool_caller
from ..context import Context
from ..discovery import service as discovery
from ..models import ToolCreate, ToolFinding, ToolFlag, ToolMatch, ToolSchedule
from ..verify.findings import FindingError

router = APIRouter(prefix="/tools", tags=["Agent tools"])


@router.get("/records/{service_id}", operation_id="get_record",
            summary="HSDS service + open findings + memory notes for one record")
def get_record(service_id: str, ctx: Context = Depends(ctx_dep), caller: str = Depends(tool_caller)):
    item = ctx.repo.index_item(service_id)
    doc = ctx.repo.render_service(service_id)
    if not item or not doc:
        raise HTTPException(404, "record not found")
    return {
        "service": doc,
        "status": {k: item.get(k) for k in ("verification_status", "unverified_reason", "last_check_at",
                                            "last_check_category", "source", "publish_state")},
        "open_findings": [{k: f.get(k) for k in ("finding_id", "category", "field", "current_value",
                                                 "proposed_value", "model_id", "checked_at", "what_to_ask")}
                          for f in ctx.findings.for_service(service_id, status="open")],
        "memory_notes": ctx.memory.notes(item["org_id"]) if item.get("org_id") else [],
    }


@router.post("/records/match", operation_id="match_existing",
             summary="Candidate duplicates for a facility (name, phone, address, website domain)")
def match_existing(body: ToolMatch, ctx: Context = Depends(ctx_dep), caller: str = Depends(tool_caller)):
    return {"matches": discovery.match_existing(ctx, name=body.name, phone=body.phone, address=body.address,
                                                domain=body.domain, zip_code=body.zip)}


@router.post("/records", operation_id="create_record",
             summary="Create a NEW HSDS service record (discovery-agent only); held until verified")
def create_record(body: ToolCreate, ctx: Context = Depends(ctx_dep), caller: str = Depends(tool_caller)):
    try:
        return discovery.create_record(ctx, hsds=body.hsds, evidence=[e.model_dump() for e in body.evidence],
                                       run_id=body.run_id, caller=caller)
    except discovery.DiscoveryError as exc:
        raise HTTPException(exc.status, str(exc)) from None


@router.post("/findings", operation_id="record_finding",
             summary="Record one evidence-backed finding (writes re-findings, never HSDS)")
def record_finding(body: ToolFinding, ctx: Context = Depends(ctx_dep), caller: str = Depends(tool_caller)):
    if not ctx.repo.index_item(body.service_id):
        raise HTTPException(404, "record not found")
    try:
        f = ctx.findings.create(
            service_id=body.service_id, category=body.category, field=body.field,
            current_value=body.current_value, proposed_value=body.proposed_value,
            evidence=[e.model_dump() for e in body.evidence], confidence=body.confidence,
            model_id=body.model_id or ctx.settings.bedrock_model_id, agent_session_id=body.agent_session_id,
            what_to_ask=body.what_to_ask, note="ai_generated" if body.ai_generated else "", source=caller)
    except FindingError as exc:
        raise HTTPException(422, str(exc)) from None
    return {"finding_id": f["finding_id"], "status": f["status"]}


@router.post("/flags", operation_id="flag_for_specialist",
             summary="Ask a specialist to check something that can't be settled online")
def flag_for_specialist(body: ToolFlag, ctx: Context = Depends(ctx_dep), caller: str = Depends(tool_caller)):
    if not ctx.repo.index_item(body.service_id):
        raise HTTPException(404, "record not found")
    f = ctx.findings.create(service_id=body.service_id, category="needs_manual", field="*", note=body.reason[:500],
                            what_to_ask=[q[:200] for q in body.what_to_ask[:4]], confidence="low",
                            evidence=[e.model_dump() for e in body.evidence],
                            model_id=body.model_id or ctx.settings.bedrock_model_id,
                            agent_session_id=body.agent_session_id, source=caller)
    return {"flag_id": f["finding_id"]}


@router.post("/schedules/parse", operation_id="parse_schedule",
             summary="Free-text hours -> HSDS schedule rows (RFC 5545 freq/byday, local HH:MM)")
def parse_schedule(body: ToolSchedule, ctx: Context = Depends(ctx_dep), caller: str = Depends(tool_caller)):
    return parse_schedule_text(ctx.settings, body.text)
