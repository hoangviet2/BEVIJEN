"""Generate the HSDS v3.2.3 object reference in docs/hsds/ from the vendored schema files.

The vendored schema (backend/transform/hsds_transform/schema/) is an unmodified copy of
openreferral/specification tag v3.2.3. Generating the docs from it keeps them identical
to what the converter validates against. Do not edit the generated files by hand.

Usage (from the repository root):

    python3 docs/hsds/tools/generate_reference.py

Standard library only.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SCHEMA_DIR = ROOT / "backend" / "transform" / "hsds_transform" / "schema"
OUT_DIR = ROOT / "docs" / "hsds"
OBJ_DIR = OUT_DIR / "objects"

HSDS_VERSION = "3.2.3"
CORE_OBJECTS = ("organization", "service", "location", "service_at_location")
GENERATED_NOTE = (
    "<!-- GENERATED by docs/hsds/tools/generate_reference.py from the vendored HSDS "
    f"v{HSDS_VERSION} schema. Do not edit by hand. -->"
)
ONLINE_REF = "https://docs.openreferral.org/en/latest/hsds/schema_reference.html"

# Foreign-key columns whose name does not equal "<table>_id".
FK_SPECIAL = {
    ("taxonomy_term", "parent_id"): "taxonomy_term",
    ("organization", "parent_organization_id"): "organization",
}
# Polymorphic links: the target table is named by another column.
POLYMORPHIC = {
    ("attribute", "link_id"): "any object; `link_entity` names its table",
    ("metadata", "resource_id"): "any object, named by `resource_type`",
}
# Columns ending in _id that are not references to another HSDS row.
NOT_FK = {("organization", "tax_id")}


def load() -> dict[str, dict]:
    schemas = {}
    for path in sorted(SCHEMA_DIR.glob("*.json")):
        if path.name == "tabular.json":
            continue
        schemas[path.stem] = json.loads(path.read_text(encoding="utf-8"))
    return schemas


def ref_target(spec: dict) -> tuple[str, bool] | None:
    """Return (table, many) for a nested property, else None."""
    if spec.get("type") == "array" and "$ref" in spec.get("items", {}):
        return spec["items"]["$ref"].removesuffix(".json"), True
    if "$ref" in spec:
        return spec["$ref"].removesuffix(".json"), False
    return None


def fk_target(table: str, field: str, tables: set[str]) -> str | None:
    if (table, field) in NOT_FK or (table, field) in POLYMORPHIC:
        return None
    if (table, field) in FK_SPECIAL:
        return FK_SPECIAL[(table, field)]
    if field.endswith("_id") and field[:-3] in tables:
        return field[:-3]
    return None


def cell(text) -> str:
    if text is None:
        return ""
    text = " ".join(str(text).split())
    return text.replace("|", "\\|")


def type_label(spec: dict) -> str:
    target = ref_target(spec)
    if target:
        name, many = target
        return f"array[{name}]" if many else f"object ({name})"
    return spec.get("type", "")


def render_object(name: str, schema: dict, schemas: dict, tables: set[str], reverse: dict) -> str:
    props = schema["properties"]
    required = set(schema.get("required", []))
    lines = [GENERATED_NOTE, "", f"# `{name}`", ""]
    kind = "Core object" if name in CORE_OBJECTS else "Object"
    lines += [
        f"{kind} · HSDS v{HSDS_VERSION} · tabular file `{schema.get('path', '')}` · "
        f"[online reference]({ONLINE_REF}#{name.replace('_', '-')})",
        "",
        f"> {cell(schema.get('description', ''))}",
        "",
        f"**Required:** {', '.join(f'`{r}`' for r in schema.get('required', [])) or 'none'}",
        "",
        "## Fields",
        "",
        "Scalar fields are the columns of the tabular (CSV) form. Nested fields exist only in "
        "the JSON form, where the related objects are embedded (dereferenced).",
        "",
        "| Field | Title | Type | Format | Req | Core | Allowed values | Description | Example |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for prop, spec in props.items():
        fmt = spec.get("format") or ""
        dp = spec.get("datapackage_type")
        if dp and dp != fmt:
            fmt = f"{fmt} ({dp})".strip() if fmt else f"tabular: {dp}"
        enum = ", ".join(f"`{e}`" for e in spec.get("enum", []))
        example = spec.get("example", "")
        if isinstance(example, (dict, list)):
            example = ""
        lines.append(
            f"| `{prop}` | {cell(spec.get('title'))} | {type_label(spec)} | {cell(fmt)} | "
            f"{'**yes**' if prop in required else ''} | {'Y' if spec.get('core') == 'Y' else ''} | "
            f"{enum} | {cell(spec.get('description'))} | {cell(example)} |"
        )

    nested = [(p, *ref_target(s)) for p, s in props.items() if ref_target(s)]
    fks = [(p, fk_target(name, p, tables)) for p in props]
    fks = [(p, t) for p, t in fks if t]
    poly = [(p, d) for (t, p), d in POLYMORPHIC.items() if t == name]

    lines += ["", "## Relationships", ""]
    if fks or poly:
        lines += ["**References (tabular foreign keys):**", ""]
        lines += [f"- `{p}` → [`{t}`]({t}.md)`.id`" for p, t in fks]
        lines += [f"- `{p}` → {d}" for p, d in poly]
        lines.append("")
    if nested:
        lines += ["**Embeds (JSON form):**", ""]
        lines += [
            f"- `{p}` → {'many' if many else 'one'} [`{t}`]({t}.md)" for p, t, many in nested
        ]
        lines.append("")
    refs = reverse.get(name, [])
    if refs:
        lines += ["**Referenced by:**", ""]
        lines += [f"- [`{t}`]({t}.md)`.{p}`" for t, p in refs]
        lines.append("")
    if not (fks or poly or nested or refs):
        lines += ["None.", ""]
    return "\n".join(lines).rstrip() + "\n"


def render_index(schemas: dict) -> str:
    lines = [
        GENERATED_NOTE,
        "",
        f"# HSDS v{HSDS_VERSION} objects",
        "",
        f"{len(schemas)} objects. The four core objects come first, then the rest in the order "
        "of the official tabular data package.",
        "",
        "| Object | Tabular file | Fields (scalar + nested) | Required fields | Description |",
        "|---|---|---|---|---|",
    ]

    def order(item):
        name, schema = item
        core = CORE_OBJECTS.index(name) if name in CORE_OBJECTS else 99
        return core, schema.get("datapackage_metadata", {}).get("order", 999), name

    for name, schema in sorted(schemas.items(), key=order):
        props = schema["properties"]
        nested = sum(1 for s in props.values() if ref_target(s))
        req = ", ".join(f"`{r}`" for r in schema.get("required", []))
        star = " (core)" if name in CORE_OBJECTS else ""
        lines.append(
            f"| [`{name}`]({name}.md){star} | `{schema.get('path', '')}` | "
            f"{len(props) - nested} + {nested} | {req} | {cell(schema.get('description'))} |"
        )
    return "\n".join(lines) + "\n"


def render_relationships(schemas: dict, tables: set[str]) -> str:
    lines = [
        GENERATED_NOTE,
        "",
        f"# HSDS v{HSDS_VERSION} relationships",
        "",
        "HSDS has two serializations of the same model (see [overview](README.md)):",
        "",
        "- **JSON** (canonical): related objects are embedded. A `service` holds its `phones`, "
        "`schedules`, `service_at_locations` and so on. Foreign-key columns are optional there.",
        "- **Tabular data package** (CSV): one file per object, linked by `*_id` foreign keys "
        "that hold the `id` (UUID) of the related row.",
        "",
        "## Foreign keys (tabular form)",
        "",
        "| Object | Column | Points to | Required |",
        "|---|---|---|---|",
    ]
    for name, schema in sorted(schemas.items()):
        req = set(schema.get("required", []))
        for prop in schema["properties"]:
            target = fk_target(name, prop, tables)
            if target:
                lines.append(
                    f"| `{name}` | `{prop}` | `{target}.id` | {'yes' if prop in req else ''} |"
                )
            elif (name, prop) in POLYMORPHIC:
                lines.append(f"| `{name}` | `{prop}` | {POLYMORPHIC[(name, prop)]} | |")
    lines += [
        "",
        "## Nested properties (JSON form)",
        "",
        "`many` is a JSON array (1:many). `one` is a single embedded object (1:1).",
        "",
        "| Object | Property | Embeds | Cardinality |",
        "|---|---|---|---|",
    ]
    for name, schema in sorted(schemas.items()):
        for prop, spec in schema["properties"].items():
            target = ref_target(spec)
            if target:
                lines.append(
                    f"| `{name}` | `{prop}` | `{target[0]}` | {'many' if target[1] else 'one'} |"
                )
    lines += [
        "",
        "## Diagram (core objects and their direct children)",
        "",
        "```mermaid",
        "erDiagram",
    ]
    seen = set()
    for name, schema in sorted(schemas.items()):
        for prop in schema["properties"]:
            target = fk_target(name, prop, tables)
            if target and (target in CORE_OBJECTS or name in CORE_OBJECTS) and target != name:
                key = (target, name, prop)
                if key not in seen:
                    seen.add(key)
                    lines.append(f'    {target} ||--o{{ {name} : "{prop}"')
    lines += ["```", ""]
    return "\n".join(lines)


def main() -> None:
    schemas = load()
    tables = set(schemas)
    reverse: dict[str, list[tuple[str, str]]] = {}
    for name, schema in schemas.items():
        for prop in schema["properties"]:
            target = fk_target(name, prop, tables)
            if target:
                reverse.setdefault(target, []).append((name, prop))
    OBJ_DIR.mkdir(parents=True, exist_ok=True)
    for name, schema in schemas.items():
        (OBJ_DIR / f"{name}.md").write_text(
            render_object(name, schema, schemas, tables, reverse), encoding="utf-8"
        )
    (OBJ_DIR / "README.md").write_text(render_index(schemas), encoding="utf-8")
    (OUT_DIR / "relationships.md").write_text(
        render_relationships(schemas, tables), encoding="utf-8"
    )
    print(f"Wrote {len(schemas)} object pages, objects/README.md and relationships.md")


if __name__ == "__main__":
    main()
